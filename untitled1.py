"""### Training and Evaluating Decision Tree Models
As requested, we will now build and evaluate **Decision Tree** models for both our regression and classification tasks to see how they perform compared to the Random Forest models.
"""

from sklearn.tree import DecisionTreeRegressor, DecisionTreeClassifier
from sklearn.metrics import mean_absolute_error, r2_score, accuracy_score, classification_report

# --- 1. Decision Tree Regressor (Predicting Calories) ---
dt_reg = DecisionTreeRegressor(random_state=42, max_depth=5)
dt_reg.fit(X_train, y_train)

y_pred_reg_dt = dt_reg.predict(X_test)
mae_dt = mean_absolute_error(y_test, y_pred_reg_dt)
r2_dt = r2_score(y_test, y_pred_reg_dt)

print("=== Decision Tree Regressor Performance ===")
print(f"Mean Absolute Error (MAE): {mae_dt:.2f} Calories")
print(f"R-squared (R²) Score: {r2_dt*100:.2f}%")

# --- 2. Decision Tree Classifier (Predicting Calorie Class) ---
dt_clf = DecisionTreeClassifier(random_state=42, max_depth=5)
dt_clf.fit(X_train_c, y_train_c)

y_pred_clf_dt = dt_clf.predict(X_test_c)
accuracy_dt = accuracy_score(y_test_c, y_pred_clf_dt)

print("\n=== Decision Tree Classifier Performance ===")
print(f"Overall Accuracy: {accuracy_dt*100:.2f}%")
print("\nClassification Report:")
print(classification_report(y_test_c, y_pred_clf_dt))

